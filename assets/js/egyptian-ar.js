  const attrNames = ['placeholder', 'title', 'aria-label', 'alt'];
  const skipped = 'script,style,noscript,textarea,code,pre';

  function translate(value) {
    const original = String(value ?? '');
    const trimmed = original.trim();
    const translated = Object.prototype.hasOwnProperty.call(textMap, trimmed)
      ? textMap[trimmed]
      : trimmed.replace(/NUSC Student Hub/g, 'منصة NUSC');
    if (translated === trimmed) return value;
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    return leading + translated + trailing;
  }

  function translateAttributes(el) {
    if (!(el instanceof Element)) return;
    attrNames.forEach(name => {
      if (!el.hasAttribute(name)) return;
      const before = el.getAttribute(name);
      const after = translate(before);
      if (after !== before) el.setAttribute(name, after);
    });
  }

  function scan(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      if (!root.parentElement?.closest(skipped)) {
        const before = root.nodeValue || '';
        const after = translate(before);
        if (after !== before) root.nodeValue = after;
      }
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root !== document) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateAttributes(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return node.parentElement?.closest(skipped) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    let node;
    while ((node = walker.nextNode())) {
      const before = node.nodeValue || '';
      const after = translate(before);
      if (after !== before) node.nodeValue = after;
    }
    if (root.querySelectorAll) root.querySelectorAll('[placeholder],[title],[aria-label],[alt]').forEach(translateAttributes);
  }

  function init() {
    document.documentElement.lang = 'ar-EG';
    document.documentElement.dir = 'rtl';
    scan(document.documentElement);
    const observer = new MutationObserver(records => {
      records.forEach(record => {
        if (record.type === 'childList') record.addedNodes.forEach(scan);
        else if (record.type === 'characterData') {
          const before = record.target.nodeValue || '';
          const after = translate(before);
          if (after !== before) record.target.nodeValue = after;
        } else if (record.type === 'attributes') translateAttributes(record.target);
      });
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: attrNames
    });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
