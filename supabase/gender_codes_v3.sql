-- توسيع إضافي: تطبيع الحروف + قاعدة "عبد" + أسماء حقيقية من الدفعة
CREATE OR REPLACE FUNCTION private.infer_gender_from_name(name text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  first text;
  trimmed text;
  norm text;
BEGIN
  IF name IS NULL THEN RETURN NULL; END IF;
  trimmed := btrim(name);
  IF trimmed = '' THEN RETURN NULL; END IF;

  -- تطبيع: إزالة التشكيل + توحيد الألف/الهاء/الياء
  norm := regexp_replace(trimmed, '[\u0610-\u061a\u064b-\u065f\u0670]', '', 'g');
  norm := translate(btrim(lower(norm)), 'أإآىة', 'اايه');
  IF norm = '' THEN RETURN NULL; END IF;

  -- الأسماء المركبة "نور الدين" أو "عبد الرحمن" = ذكر
  IF norm ~ '^نور\s+الدين' THEN RETURN 'male'; END IF;
  IF norm ~ '^عبد\s+' THEN RETURN 'male'; END IF;

  first := split_part(norm, ' ', 1);

  IF first IN (
    -- ذكور — شائعة
    'يوسف','عمر','احمد','محمود','محمد','مروان','فارس','موسي','موسى','عبدالله','كريم','هشام',
    'حسن','حسين','اسامه','أسامة','عمار','عادل','زياد','علي','مصطفى','ابراهيم','إسماعيل','اسماعيل',
    'طارق','حسام','وائل','اسلام','إسلام','ايمن','أيمن','رامز','حمدي','صلاح','جمال','سعيد','ثروت','شريف',
    'عاصم','خالد','مدحت','اشرف','أشرف','هيثم','امين','أمين','صبحي','سامي','سامر','رامي','باسل',
    -- ذكور — الأقباط
    'جورج','جون','انطون','أنطون','انطوني','بطرس','بولس','مرقس','مارون','شنوده','اسيوط','متياس','فيلوباتير',
    'كيرلس','ماريو','جرجس','الياس','اثناسيوس','يوحنا','يوحنس','متي','متى','انجيل','ميلاد','فادي',
    -- ذكور — تكملة من الدفعة الحقيقية
    'ادم','ادهم','اسامة','اياد','بسام','دهب','طه','عبدالحكيم','عبدالرحيم','عبدالكريم','عبدالمنعم','عبدالمجيد',
    'عمران','عمرو','ادهم','ادم','اياه','اياد','اياه','ادم','يوسف','علي','عبدالله','عبدالله',
    'فادى','كمال','مؤمن','مازن','مالك','مرهان','معاذ','مهند','وليد','يوليوس','جورج','جون','ادهم','ادم',
    'زكريا','اسحق','اسحاق','حمزه','آدم','جبر','وسيم','مرسى','نبيل','خالد','اياد',
    'ناجي','نجيب','يعقوب','يوحنا','اديب','شريف','يساه','جبر','اسحق','هشام','اسيف',
    'adam','omar','ahmed','ahmad','mahmoud','mohamed','mohammed','marawan','kareem','yusuf','youssef','ibrahim','george','john'
  ) THEN
    RETURN 'male';
  END IF;

  IF first IN (
    -- إناث — شائعة
    'ساره','سلمى','حنين','عائشه','حبيبه','يارا','منار','منه','منى','نور',
    'مريم','هبه','هبة','هاجر','رانيا','ياسمين','رنا','دينا','ندى','شيماء','اسماء','أسماء',
    -- إناث — تكملة من الدفعة الحقيقية
    'اروى','الاء','ألاء','امينه','اروى','بسنت','جنه','جنه','جودي','حبيبه','حمده','خلود',
    'داليا','رحمه','رحمه','شذى','غاده','غادة','ليلى','ليلى','مارينا','مى','مي','ميريانس','ندا','ولاء',
    -- إناث — المسيحيات
    'ماريان','ميرنا','ميرفت','كرستين','جيلان','كريستين','ساندي','ميرهان',
    -- إناث — شائعات إضافية
    'ريم','جنه','جنان','سجى','اية','آية','روان','صبا','صفاء','دعاء','ملك','تقى','فريده',
    'كارما','لارا','مايا','سمر','سما','نوران','رؤى','هيام','شهد','رغد','وجدان',
    'هاله','جومانا','دانا','لين','ايلين','ليان','ليا','ميرا','ميرال','حور','ماريا','بيسان','ريناد','رناد','رنيم','تالا','تالين',
    'هنا','هناء','تسنيم','جنا','ثراء','جيهان','جواهر','امل','آلاء','إيناس','ايناس','هيام','صبريه','صبرية','نصرة',
    'sara','salma','hanin','habiba','yara','aya','mariam','noor','noura','dina','rana','yasmin','manar','menna','saly','solomia'
  ) THEN
    RETURN 'female';
  END IF;

  RETURN NULL;
END;
$$;

-- إعادة الملء بقائمة أوسع
UPDATE public.student_codes
SET gender = private.infer_gender_from_name(full_name)
WHERE gender IS NULL;
