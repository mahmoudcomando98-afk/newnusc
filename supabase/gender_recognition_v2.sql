-- توسيع التعرف التلقائي على الجنس — قائمة أوسع من الأسماء المصرية
-- شغّل بعد gender_recognition.sql

CREATE OR REPLACE FUNCTION private.infer_gender_from_name(name text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  first text;
  trimmed text;
BEGIN
  IF name IS NULL THEN RETURN NULL; END IF;
  trimmed := btrim(name);
  IF trimmed = '' THEN RETURN NULL; END IF;
  -- الاسم المركب "نور الدين" = ذكر
  IF trimmed ~ '^نور\s+الدين' THEN RETURN 'male'; END IF;
  first := lower(split_part(trimmed, ' ', 1));

  IF first IN (
    -- ذكور — الأكثر شيوعًا
    'يوسف','عمر','احمد','أحمد','محمود','محمد','مروان','فارس','موسي','موسى','عبدالله','كريم','هشام',
    'حسن','حسين','اسامة','أسامة','عمار','عادل','زياد','علي','مصطفى','ابراهيم','إسماعيل','اسماعيل',
    'طارق','حسام','وائل','اسلام','إسلام','ايمن','أيمن','رامز','حمدي','صلاح','جمال','سعيد','ثروت','شريف',
    'عاصم','خالد','مدحت','اشرف','أشرف','هيثم','امين','أمين','صبحي','سامي','سامر','رامي','باسل',
    -- ذكور — تكملة
    'جوزيف','مرقس','شنودة','بولس','بيشوى','ماريو','انطون','أنطون','امير','أمير','حنا','ريان','حمزه','حمزة',
    'نادر','حماده','حمادة','شعبان','رمضان','فتحي','فوزي','مجدي','سيد','سيّد','نبيل','هاني','وسيم',
    'ميلاد','فادي','كيرلس','جرجس','بطرس','راشد','جبر','وفيق','ريان','آدم','تامر','وسام','ممدوح',
    'جابر','السعيد','شحاته','شحاتة','بطرس','شكري','ابو','أبو','عطوه','طاحون','زكريا','اسحق','إسحاق',
    'آدم','بشار','بيير','جاك','جان','جرجس','جوزف','مارون','نعيم','هاني','سامي','امجد','كارم','همام',
    'بلال','جلال','عثمان','علوي','فرج','قاسم','لؤي','ماجد','ماهر','ناجي','نجيب','يعقوب','يوحنا',
    'adam','omar','ahmed','ahmad','mahmoud','mohamed','mohammed','marawan','kareem','yusuf','youssef','yusuf','ibrahim','mezo','akmok'
  ) THEN
    RETURN 'male';
  END IF;

  IF first IN (
    -- إناث — الأكثر شيوعًا
    'ساره','سارة','سلمى','حنين','عائشه','عائشة','حبيبة','يارا','منار','منة','منه','نور',
    'مريم','هبة','هبه','هاجر','رانيا','ياسمين','رنا','دينا','ندى','شيماء','اسماء','أسماء',
    -- إناث — تكملة
    'ريم','جنى','جنان','سجى','اية','آية','روان','صبا','صفاء','دعاء','ملك','تقى','تقة','فريدة',
    'كارما','لارا','مايا','سمر','سما','نوران','رؤى','هيام','شهد','رشا','رغد','وجدان',
    'هالة','جومانا','دانا','لين','ايلين','إيلين','ليان','ليا','ميرا','ميرال','حور','شيراز','ماريا',
    'مارى','كريستين','ياسنت','بيسان','ريناد','رناد','رنيم','تالا','تالين','ملك','هنا','هناء','تسنيم',
    'جنى','جنا','ثراء','جيهان','جواهر','أمل','امل','إيلاف','آلاء','إيمان','ايمان','إيناس','ايناس','ايمان',
    'براءة','رشا','رهام','رهف','روز','ريم','سارة','سلمى','سوار','نيللي','رواء','ريما','سالار','سالمة',
    'sam','sara','salma','hanin','habiba','yara','aya','mariam','noor','noura','dina','rana','yasmin','hana','hanaa',
    'menna','mona','mahm','sara','hoda','nada','ranim','layan','layan','doaa','roua','amira','sarah','سارة'
  ) THEN
    RETURN 'female';
  END IF;

  RETURN NULL;
END;
$$;

-- على الـ users اللي لسه بدون نوع — جرّب الاستنتاج تاني بقائمة أوسع
UPDATE public.profiles
SET gender = private.infer_gender_from_name(full_name)
WHERE gender IS NULL;
